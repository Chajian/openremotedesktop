const RETURN_BASE = "http://return-to.invalid";
export function safeLangReturnTo(value: unknown): string {
  if (typeof value !== "string" || value.length > 8192 || /[\\\r\n\0#]/.test(value) || !value.startsWith("/") || value.startsWith("//")) return "/dashboard";
  let url: URL;
  try {
    url = new URL(value, RETURN_BASE);
  } catch {
    return "/dashboard";
  }
  if (url.origin !== RETURN_BASE) return "/dashboard";
  // Whitelist the WHATWG-normalized path, never the raw string: "%2e%2e" and ".%2E" are dot segments too.
  const path = url.pathname;
  const allowed = path === "/dashboard" || path.startsWith("/dashboard/") || path === "/device" || path === "/oauth/authorize";
  return allowed ? path + url.search : "/dashboard";
}
export function formatDate(locale: Locale, ts: number): string {
  return new Intl.DateTimeFormat(locale, { month: "short", day: "numeric" }).format(ts);
}
export function formatDateTime(locale: Locale, ts: number): string {
  return new Intl.DateTimeFormat(locale, { year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }).format(ts);
}
export function formatRelative(locale: Locale, ts: number | null, now: number): string {
  if (ts === null) return t(locale, "time.never");
  const seconds = Math.round((ts - now) / 1000);
  const abs = Math.abs(seconds);
  if (abs < 45) return t(locale, "time.justNow");
  // "always" keeps digits ("2 days ago" / "2天前"); "auto" would produce "前天".
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "always" });
  if (abs < 3600) return rtf.format(Math.round(seconds / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(seconds / 3600), "hour");
  if (abs < 7 * 86400) return rtf.format(Math.round(seconds / 86400), "day");
  return formatDate(locale, ts);
}
