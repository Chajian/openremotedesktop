const catalogs: Record<Locale, Record<MessageKey, string>> = { en, "zh-CN": zhCN };

export function t(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}
export function catalogKeys(locale: Locale): string[] { return Object.keys(catalogs[locale]).sort(); }

function cookieLocale(header: string | undefined): Locale | null {
  const value = /(?:^|;\s*)odr_lang=([^;]+)/.exec(header ?? "")?.[1];
  return value === "en" || value === "zh-CN" ? value : null;
}
function headerLocale(header: string | undefined): Locale | null {
  const ranked = (header ?? "").split(",").map((part, index) => {
    const [tag = "", ...params] = part.trim().split(";");
    const q = params.map((p) => /^q=([\d.]+)$/.exec(p.trim())?.[1]).find((v) => v !== undefined);
    return { tag: tag.trim().toLowerCase(), q: q === undefined ? 1 : Number(q), index };
  }).filter((entry) => entry.tag && entry.q > 0).sort((a, b) => b.q - a.q || a.index - b.index);
  for (const { tag } of ranked) {
    if (tag === "zh" || tag.startsWith("zh-")) return "zh-CN";
    if (tag === "en" || tag.startsWith("en-")) return "en";
  }
  return null;
}
export function resolveLocale(input: { cookie?: string | undefined; acceptLanguage?: string | undefined }): Locale {
  return cookieLocale(input.cookie) ?? headerLocale(input.acceptLanguage) ?? DEFAULT_LOCALE;
}
export function localeFromRequest(request: FastifyRequest): Locale {
  const accept = request.headers["accept-language"];
  return resolveLocale({ cookie: request.headers.cookie, acceptLanguage: Array.isArray(accept) ? accept.join(",") : accept });
}
